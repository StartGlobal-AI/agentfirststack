/**
 * How the recorder describes an element an agent will read about: a stable CSS selector, whether
 * it is interactive, and a short label. Written against a structural element type (no DOM lib), so
 * the browser passes real elements and unit tests pass small fakes.
 */

export interface El {
  tagName: string;
  id: string;
  parentElement: El | null;
  getAttribute(name: string): string | null;
  classList?: ArrayLike<string>;
  children?: ArrayLike<El>;
  textContent?: string | null;
}

const MAX_DEPTH = 5;
const MAX_SELECTOR = 240;
const MAX_LABEL = 80;

/** Minimal CSS.escape for identifiers (ids and classes). */
export function cssEscape(s: string): string {
  let out = "";
  for (let i = 0; i < s.length; i++) {
    const ch = s[i]!;
    const code = ch.charCodeAt(0);
    if (/[A-Za-z0-9_-]/.test(ch) || code >= 0x80) {
      if (i === 0 && /[0-9]/.test(ch)) out += `\\3${ch} `;
      else if (i === 1 && /[0-9]/.test(ch) && s[0] === "-") out += `\\3${ch} `;
      else out += ch;
    } else out += `\\${ch}`;
  }
  return out;
}

const attrValue = (v: string) => v.replace(/["\\]/g, "\\$&");

/** Ids generated by frameworks (React useId ":r1:", "ember123", uuids, hashes) change between page loads. */
export function stableId(id: string): boolean {
  return !!id && id.length <= 50 && !/^\d|:|\d{3,}|[0-9a-f]{10,}|\s/i.test(id);
}

/** CSS-in-JS and hashed module classes ("css-1x2y3z", "sc-AxjAm", "Button_root__3hNo2") and utility noise. */
export function stableClass(c: string): boolean {
  if (!c || c.length > 30) return false;
  if (/[:[\]/.!@#%&*()=+,]/.test(c)) return false; // tailwind variants, arbitrary values
  if (/^(css|sc|jsx|emotion|styled|svelte)-/i.test(c)) return false;
  if (/__[A-Za-z0-9]{4,}$/.test(c) || /[A-Za-z]_[A-Za-z0-9]{5}$/.test(c)) return false; // css modules
  if (/\d{3,}/.test(c)) return false;
  if (/^[a-z]+-[A-Za-z0-9]{5,}$/.test(c) && /\d/.test(c) && /[A-Z]|[a-z]\d|\d[a-z]/.test(c.split("-")[1] ?? "")) return false;
  return true;
}

const TEST_ATTRS = ["data-testid", "data-test", "data-test-id", "data-cy", "data-qa", "data-afsr-id"];

function part(el: El): { text: string; anchor: boolean } {
  const tag = el.tagName.toLowerCase();
  if (el.id && stableId(el.id)) return { text: `#${cssEscape(el.id)}`, anchor: true };
  for (const a of TEST_ATTRS) {
    const v = el.getAttribute(a);
    if (v && v.length <= 60) return { text: `${tag}[${a}="${attrValue(v)}"]`, anchor: true };
  }
  let s = tag;
  if (tag === "input" || tag === "select" || tag === "textarea" || tag === "button") {
    const name = el.getAttribute("name");
    if (name && name.length <= 40 && !/\d{3,}/.test(name)) s += `[name="${attrValue(name)}"]`;
  }
  const classes = el.classList ? Array.from(el.classList).filter(stableClass).slice(0, 2) : [];
  for (const c of classes) s += `.${cssEscape(c)}`;
  const parent = el.parentElement;
  if (parent?.children && tag !== "body" && tag !== "html") {
    const same = Array.from(parent.children).filter((c) => c.tagName === el.tagName);
    if (same.length > 1) s += `:nth-of-type(${same.indexOf(el) + 1})`;
  }
  return { text: s, anchor: false };
}

/**
 * A selector that finds the element again on the live page and stays the same across visits:
 * anchored at the nearest stable id or test attribute, at most 5 levels deep.
 */
export function stableSelector(el: El): string {
  const parts: string[] = [];
  let cur: El | null = el;
  for (let depth = 0; cur && depth < MAX_DEPTH; depth++) {
    const tag = cur.tagName.toLowerCase();
    if (tag === "html") break;
    const p = part(cur);
    parts.unshift(p.text);
    if (p.anchor || tag === "body") break;
    cur = cur.parentElement;
  }
  const sel = parts.join(" > ");
  return sel.length > MAX_SELECTOR ? sel.slice(sel.length - MAX_SELECTOR).replace(/^[^>]*>\s*/, "") : sel;
}

const INTERACTIVE_TAGS = new Set(["button", "input", "select", "textarea", "label", "summary", "option", "details"]);
const INTERACTIVE_ROLES = new Set([
  "button",
  "link",
  "tab",
  "menuitem",
  "menuitemcheckbox",
  "menuitemradio",
  "checkbox",
  "radio",
  "switch",
  "option",
  "combobox",
  "slider",
  "treeitem",
]);

export function isInteractive(el: El): boolean {
  const tag = el.tagName.toLowerCase();
  if (tag === "a" || tag === "area") return el.getAttribute("href") !== null;
  if (INTERACTIVE_TAGS.has(tag)) return true;
  const role = el.getAttribute("role");
  if (role && INTERACTIVE_ROLES.has(role.toLowerCase())) return true;
  if (el.getAttribute("onclick") !== null) return true;
  const ti = el.getAttribute("tabindex");
  if (ti !== null && ti !== "-1") return true;
  const ce = el.getAttribute("contenteditable");
  return ce === "" || ce === "true";
}

/** The element a click "means": the nearest interactive ancestor (an SVG icon inside a button -> the button). */
export function clickTarget(el: El): { el: El; interactive: boolean } {
  let cur: El | null = el;
  for (let depth = 0; cur && depth < 8; depth++) {
    const tag = cur.tagName.toLowerCase();
    if (tag === "body" || tag === "html") break;
    if (isInteractive(cur)) return { el: cur, interactive: true };
    cur = cur.parentElement;
  }
  return { el, interactive: false };
}

const collapse = (s: string) => s.replace(/\s+/g, " ").trim();
const clip = (s: string, n: number) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);

function childCount(el: El): number {
  return el.children ? el.children.length : 0;
}

/**
 * The text a person would call the element by: aria-label, a button's value, an image's alt, its
 * own text (only for small elements: a click on a page-wide container gets no label), or its
 * title. Input values are never used. `text` reads the element's text; the recorder passes one
 * that masks each descendant by its own rule and skips blocked ones (default: textContent).
 */
export function rawLabel(el: El, text?: (el: El) => string): string {
  const aria = el.getAttribute("aria-label");
  if (aria && collapse(aria)) return clip(collapse(aria), MAX_LABEL);
  const tag = el.tagName.toLowerCase();
  if (tag === "input") {
    const type = (el.getAttribute("type") ?? "text").toLowerCase();
    if (type === "submit" || type === "button" || type === "reset") return clip(collapse(el.getAttribute("value") ?? type), MAX_LABEL);
    if (type === "image") return clip(collapse(el.getAttribute("alt") ?? ""), MAX_LABEL);
    return clip(collapse(el.getAttribute("placeholder") ?? ""), MAX_LABEL);
  }
  if (tag === "select" || tag === "textarea") return clip(collapse(el.getAttribute("placeholder") ?? ""), MAX_LABEL);
  if (tag === "img") return clip(collapse(el.getAttribute("alt") ?? el.getAttribute("title") ?? ""), MAX_LABEL);
  if (childCount(el) <= 12) {
    const own = collapse((text ? text(el) : (el.textContent ?? "")).slice(0, 2000));
    if (own) return clip(own, MAX_LABEL);
  }
  const title = el.getAttribute("title");
  return title ? clip(collapse(title), MAX_LABEL) : "";
}

/** "a", "button", "input[type=email]", ... */
export function tagDescriptor(el: El): string {
  const tag = el.tagName.toLowerCase();
  if (tag === "input") return `input[type=${(el.getAttribute("type") ?? "text").toLowerCase().replace(/[^a-z-]/g, "")}]`;
  return tag;
}
